const currencySymbols: Record<Currency, string> = {
  USD: '$',
  EUR: '€',
  GBP: '£',
  BRL: 'R$',
  CNY: '¥',
  INR: '₹',
};

export const TranslationProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<Language>('en');
  const [currency, setCurrency] = useState<Currency>('USD');
  const [oddsFormat, setOddsFormat] = useState<OddsFormat>('decimal');

  // Load from localStorage on mount
  useEffect(() => {
    const savedLang = localStorage.getItem('language') as Language;
    const savedCurr = localStorage.getItem('currency') as Currency;
    const savedOdds = localStorage.getItem('oddsFormat') as OddsFormat;

    if (savedLang && translations[savedLang]) setLanguage(savedLang);
    if (savedCurr && currencySymbols[savedCurr]) setCurrency(savedCurr);
    if (savedOdds) setOddsFormat(savedOdds);
  }, []);

  // Save to localStorage on change
  useEffect(() => {
    localStorage.setItem('language', language);
  }, [language]);

  useEffect(() => {
    localStorage.setItem('currency', currency);
  }, [currency]);

  useEffect(() => {
    localStorage.setItem('oddsFormat', oddsFormat);
  }, [oddsFormat]);

  const t = (key: string): string => {
    return translations[language][key] || key;
  };

  const formatCurrency = (amount: number): string => {
    const symbol = currencySymbols[currency];
    // Simple currency conversion simulation (just format, logic would be backend)
    // For demo purposes, we just change the symbol
    return `${symbol}${amount.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  };

  return (
    <TranslationContext.Provider value={{
      language,
      setLanguage,
      currency,
      setCurrency,
      oddsFormat,
      setOddsFormat,
      t,
      formatCurrency
    }}>
      {children}
    </TranslationContext.Provider>
  );
};

export const useTranslation = () => {
  const context = useContext(TranslationContext);
  if (context === undefined) {
    throw new Error('useTranslation must be used within a TranslationProvider');
  }
  return context;
};
